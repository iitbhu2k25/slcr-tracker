-- SLCR Progress Tracker — Supabase schema.
-- Run once in Supabase Dashboard → SQL Editor → New query → paste → Run.
--
-- The app talks to these tables only from the server, with the service-role key.
-- RLS is enabled with no policies, so the public anon key cannot read or write anything.

create table if not exists public.users (
  id              bigint generated by default as identity primary key,
  username        text not null unique,
  password_hash   text not null,
  pw_version      integer not null default 1,
  role            text not null check (role in ('admin', 'staff')),
  name            text not null,
  designation     text not null default '',
  emp_code        text not null default '',
  joined_on       text not null default '',
  email           text not null default '',
  phone           text not null default '',
  photo_b64       text,
  has_photo       boolean generated always as (photo_b64 is not null) stored,
  photo_version   integer not null default 0,
  active          boolean not null default true,
  must_change_pw  boolean not null default true,
  created_at      timestamptz not null default now(),
  last_login      timestamptz
);

create table if not exists public.entries (
  id             bigint generated by default as identity primary key,
  user_id        bigint not null references public.users(id) on delete cascade,
  date           date not null,
  hours          numeric(4,1) not null,
  location       text not null default '',
  category       text not null,
  status         text not null,
  title          text not null,
  work           text not null,
  outputs        text not null default '',
  next_plan      text not null default '',
  issues         text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  review_status  text not null default '' check (review_status in ('', 'reviewed', 'revision')),
  review_remark  text not null default '',
  reviewed_at    timestamptz,
  reviewed_by    bigint references public.users(id) on delete set null
);
create index if not exists entries_user_date on public.entries (user_id, date desc);
create index if not exists entries_date on public.entries (date);

create table if not exists public.login_failures (
  id   bigint generated by default as identity primary key,
  key  text not null,
  at   timestamptz not null default now()
);
create index if not exists login_failures_key_at on public.login_failures (key, at);

create table if not exists public.audit_log (
  id       bigint generated by default as identity primary key,
  at       timestamptz not null default now(),
  user_id  bigint references public.users(id) on delete set null,
  action   text not null,
  detail   text not null default ''
);

alter table public.users          enable row level security;
alter table public.entries        enable row level security;
alter table public.login_failures enable row level security;
alter table public.audit_log      enable row level security;

-- Atomic password change: bumps pw_version so every existing session is signed out.
create or replace function public.set_password(p_id bigint, p_hash text, p_must_change boolean)
returns void language sql security definer set search_path = public as $$
  update public.users
     set password_hash = p_hash, must_change_pw = p_must_change, pw_version = pw_version + 1
   where id = p_id;
$$;

create or replace function public.toggle_user_active(p_id bigint)
returns void language sql security definer set search_path = public as $$
  update public.users set active = not active where id = p_id;
$$;

create or replace function public.bump_photo(p_id bigint, p_photo text)
returns void language sql security definer set search_path = public as $$
  update public.users set photo_b64 = p_photo, photo_version = photo_version + 1 where id = p_id;
$$;

revoke execute on function public.set_password(bigint, text, boolean) from public, anon, authenticated;
revoke execute on function public.toggle_user_active(bigint)         from public, anon, authenticated;
revoke execute on function public.bump_photo(bigint, text)           from public, anon, authenticated;
